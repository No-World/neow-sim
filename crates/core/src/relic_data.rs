/// 按 tier 过滤（保持 RELIC_TIERS 顺序 = `CardLibrary` 声明序）
pub fn relics_of_tier(tier: &str) -> Vec<crate::relics::RelicKind> {
    RELIC_TIERS
        .iter()
        .filter(|(_, _, t)| *t == tier)
        .map(|(_, k, _)| *k)
        .collect()
}

/// 单只遗物的 tier
pub fn relic_tier(kind: crate::relics::RelicKind) -> &'static str {
    RELIC_TIERS
        .iter()
        .find(|(_, k, _)| *k == kind)
        .map(|(_, _, t)| *t)
        .unwrap_or("SPECIAL")
}
