/// 按 tier 取预洗池（保持 Java HashMap 迭代序，见 RELIC_POOL_ITER_ORDER）
pub fn relics_of_tier(tier: &str) -> Vec<crate::relics::RelicKind> {
    RELIC_POOL_ITER_ORDER
        .iter()
        .find(|(t, _)| *t == tier)
        .map(|(_, pool)| pool.to_vec())
        .unwrap_or_default()
}

/// 单只遗物的 tier
pub fn relic_tier(kind: crate::relics::RelicKind) -> &'static str {
    RELIC_TIERS
        .iter()
        .find(|(_, k, _)| *k == kind)
        .map(|(_, _, t)| *t)
        .unwrap_or("SPECIAL")
}

