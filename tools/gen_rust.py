#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
代码生成：data/*.json → crates/core/src/generated/*.rs（静态表，零依赖、编译期检查）。
生成后需执行 cargo fmt。再生成时覆盖。
"""
import json
import sys
from pathlib import Path

DATA = Path(sys.argv[1])
OUT = Path(sys.argv[2]) / "generated"
OUT.mkdir(parents=True, exist_ok=True)
HDR = "// @generated by tools/gen_rust.py —— 勿手改；重新生成后执行 cargo fmt\n"


def s(x) -> str:
    return '"' + str(x).replace("\\", "\\\\").replace('"', '\\"') + '"'


def expr_rs(e) -> str:
    if isinstance(e, int):
        return f"Expr::N({e})"
    if isinstance(e, str):
        return {"Magic": "Expr::Magic", "DamageBase": "Expr::DamageBase",
                "BlockBase": "Expr::BlockBase", "CurrentBlock": "Expr::CurrentBlock",
                "XCost": "Expr::XCost"}.get(e, f"Expr::Raw({s(e)})")
    if isinstance(e, dict):
        if "Const" in e:
            return f"Expr::Const({s(e['Const'])})"
        if "Raw" in e:
            return f"Expr::Raw({s(e['Raw'])})"
    raise ValueError(e)


def target_rs(t: str) -> str:
    return {"Enemy": "Target::Enemy", "AllEnemies": "Target::AllEnemies",
            "Self": "Target::SelfC", "Unknown": "Target::Unknown"}.get(t, "Target::Unknown")


def effect_rs(eff) -> str:
    if "Damage" in eff:
        t, a = eff["Damage"]
        return f"Effect::Damage({target_rs(t)}, {expr_rs(a)})"
    if "DamageAll" in eff:
        return f"Effect::DamageAll({expr_rs(eff['DamageAll'])})"
    if "Block" in eff:
        return f"Effect::Block({expr_rs(eff['Block'])})"
    if "Draw" in eff:
        return f"Effect::Draw({expr_rs(eff['Draw'])})"
    if "ApplyPower" in eff:
        t, p, a = eff["ApplyPower"]
        return f"Effect::ApplyPower({target_rs(t)}, {s(p)}, {expr_rs(a)})"
    if "GainEnergy" in eff:
        return f"Effect::GainEnergy({expr_rs(eff['GainEnergy'])})"
    if "Heal" in eff:
        return f"Effect::Heal({expr_rs(eff['Heal'])})"
    if "LoseHP" in eff:
        return f"Effect::LoseHP({expr_rs(eff['LoseHP'])})"
    if "CopySelfToDiscard" in eff:
        return "Effect::CopySelfToDiscard"
    if "MakeInDiscard" in eff:
        cls, n = eff["MakeInDiscard"]
        return f"Effect::MakeInDiscard({s(cls)}, {expr_rs(n)})"
    if "ExhaustHand" in eff:
        return "Effect::ExhaustHand"
    if "DamageRandom" in eff:
        return f"Effect::DamageRandom({expr_rs(eff['DamageRandom'])})"
    if "MakeInHand" in eff:
        cls, n = eff["MakeInHand"]
        return f"Effect::MakeInHand({s(cls)}, {expr_rs(n)})"
    if "CopySelfToHand" in eff:
        return f"Effect::CopySelfToHand({expr_rs(eff['CopySelfToHand'])})"
    if "MakeInDrawRandom" in eff:
        cls, n = eff["MakeInDrawRandom"]
        return f"Effect::MakeInDrawRandom({s(cls)}, {expr_rs(n)})"
    if "MakeInDrawTop" in eff:
        cls, n = eff["MakeInDrawTop"]
        return f"Effect::MakeInDrawTop({s(cls)}, {expr_rs(n)})"
    if "Repeat" in eff:
        cnt, inner = eff["Repeat"]
        if not inner:
            return f"Effect::Repeat({expr_rs(cnt)}, &[])"
        inner_s = ",\n            ".join(effect_rs(e) for e in inner)
        return f"Effect::Repeat({expr_rs(cnt)}, &[\n            {inner_s},\n        ])"
    if "Unsupported" in eff:
        return f"Effect::Unsupported({s(eff['Unsupported'])})"
    raise ValueError(eff)


def opt(v) -> str:
    return "None" if v is None else f"Some({v})"


def gen_cards():
    data = json.loads((DATA / "cards_full.json").read_text(encoding="utf-8"))["data"]
    lines = [HDR, "use crate::effects::{CardDef, Effect, Expr, Target};\n",
             f"pub static CARDS: &[CardDef] = &["]
    for c in data:
        upg = c.get("upgrade") or {}
        effs = ",\n            ".join(effect_rs(e) for e in c.get("effects", [])) or "// 无"
        effs = f"&[\n            {effs},\n        ]" if c.get("effects") else "&[]"
        flags = f"&[{', '.join(s(f) for f in c['flags'])}]" if c.get("flags") else "&[]"
        lines.append(
            f"    CardDef {{ id: {s(c['id'])}, cls: {s(c['class'])}, color: {s(c['color'])},"
            f" card_type: {s(c.get('type'))}, rarity: {s(c.get('rarity'))},"
            f" target: {s(c.get('target'))}, cost: {opt(c.get('cost'))},"
            f" base_damage: {opt(c.get('baseDamage'))}, base_block: {opt(c.get('baseBlock'))},"
            f" base_magic: {opt(c.get('baseMagicNumber'))},"
            f" upg_damage: {opt(upg.get('damage'))}, upg_block: {opt(upg.get('block'))},"
            f" upg_magic: {opt(upg.get('magicNumber'))}, upg_base_cost: {opt(upg.get('baseCost'))},"
            f" flags: {flags}, status: {s(c.get('status'))},"
            f" effects: {effs},\n    }},")
    lines.append("];")
    (OUT / "cards.rs").write_text("\n".join(lines), encoding="utf-8")
    return len(data)


def gen_monsters():
    data = json.loads((DATA / "monsters.json").read_text(encoding="utf-8"))["data"]
    lines = [HDR, "use crate::effects::{MonsterDef, HpTier, MoveDef};\n",
             "pub static MONSTERS: &[MonsterDef] = &["]
    for m in data:
        hp = ", ".join(
            f"HpTier {{ asc: {h['asc']}, min: {opt(h.get('min'))}, max: {opt(h.get('max'))} }}"
            for h in m.get("hp", [])) or ""
        moves = []
        for mv in m.get("moves", []):
            base_v = mv.get("base") if isinstance(mv.get("base"), int) else None
            moves.append(
                f"MoveDef {{ byte: {mv['byte']}, intent: {s(mv['intent'])},"
                f" base: {opt(base_v)}, damage_from_index: {opt(mv.get('damage_from_index'))} }}")
        di = ", ".join(s(str(x)) for x in m.get("damage_infos", []))
        probs = ", ".join(f"{float(p)}" for p in m.get("ai_probabilities", []))
        tta = m.get("take_turn_actions") or {}
        tta_s = ", ".join(
            f"({b}, &[{', '.join(s(a) for a in acts)}])" for b, acts in sorted(tta.items(), key=lambda kv: int(kv[0])))
        lines.append(
            f"    MonsterDef {{ id: {s(m['id'])}, cls: {s(m['class'])},"
            f" hp: &[{hp}], moves: &[{', '.join(moves)}], damage_infos: &[{di}],"
            f" ai_probabilities: &[{probs}], take_turn_actions: &[{tta_s}] }},")
    lines.append("];")
    (OUT / "monsters.rs").write_text("\n".join(lines), encoding="utf-8")
    return len(data)


def gen_chars():
    data = json.loads((DATA / "characters.json").read_text(encoding="utf-8"))["data"]
    lines = [HDR, "use crate::effects::CharacterDef;\n",
             "pub static CHARACTERS: &[CharacterDef] = &["]
    for ch in data:
        deck = ", ".join(s(c) for c in ch["starting_deck"])
        relics = ", ".join(s(r) for r in ch["starting_relics"])
        lines.append(
            f"    CharacterDef {{ id: {s(ch['id'])}, max_hp: {opt(ch.get('max_hp'))},"
            f" starting_deck: &[{deck}], starting_relics: &[{relics}] }},")
    lines.append("];")
    (OUT / "chars.rs").write_text("\n".join(lines), encoding="utf-8")
    return len(data)


n1 = gen_cards()
n2 = gen_monsters()
n3 = gen_chars()
mod = '''// @generated 目录：由 tools/gen_rust.py 生成
mod cards;
mod chars;
mod monsters;

pub use cards::CARDS;
pub use chars::CHARACTERS;
pub use monsters::MONSTERS;

/// 按 id 查卡牌定义
pub fn find_card(id: &str) -> Option<&'static crate::effects::CardDef> {
    CARDS.iter().find(|c| c.id == id)
}

/// 按 Java 类名查卡牌定义（MakeInDiscard 等效果引用类名）
pub fn find_card_by_class(cls: &str) -> Option<&'static crate::effects::CardDef> {
    CARDS.iter().find(|c| c.cls == cls)
}

/// 按 id 查怪物定义
pub fn find_monster(id: &str) -> Option<&'static crate::effects::MonsterDef> {
    MONSTERS.iter().find(|m| m.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::effects::{Effect, Expr, Target};

    #[test]
    fn registry_counts() {
        assert!(CARDS.len() >= 370, "卡池全量 {}", CARDS.len());
        assert!(MONSTERS.len() >= 70, "怪物全量 {}", MONSTERS.len());
        assert_eq!(CHARACTERS.len(), 4);
    }

    #[test]
    fn spot_checks() {
        let bash = find_card("Bash").unwrap();
        assert!(matches!(bash.effects[0], Effect::Damage(Target::Enemy, Expr::DamageBase)));
        let cleave = find_card("Cleave").unwrap();
        assert!(matches!(cleave.effects[0], Effect::DamageAll(_)));
        let clothes = find_card("Clothesline").unwrap();
        assert!(matches!(
            clothes.effects[1],
            Effect::ApplyPower(_, "Weakened", _)
        ));
        // 愤怒：伤害 + 复制入弃牌堆
        let anger = find_card("Anger").unwrap();
        assert!(matches!(anger.effects[1], Effect::CopySelfToDiscard));
    }

    #[test]
    fn characters_data() {
        let ic = CHARACTERS.iter().find(|c| c.id == "Ironclad").unwrap();
        assert_eq!(ic.max_hp, Some(80));
        assert_eq!(ic.starting_deck.len(), 10);
        let silent = CHARACTERS.iter().find(|c| c.id == "TheSilent").unwrap();
        assert_eq!(silent.max_hp, Some(70));
        assert_eq!(silent.starting_deck.len(), 12);
    }

    #[test]
    fn jaw_worm_data() {
        let jw = find_monster("JawWorm").unwrap();
        assert!(jw.hp.iter().any(|h| h.asc == 7 && h.min == Some(42) && h.max == Some(46)));
        assert_eq!(jw.ai_probabilities.len(), 3);
    }
}
'''
(OUT / "mod.rs").write_text(mod, encoding="utf-8")
print(f"生成: cards={n1} monsters={n2} chars={n3} → {OUT}")
